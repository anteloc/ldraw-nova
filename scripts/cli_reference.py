"""Generate docs/agent/reference/commands.md from the CLI's own argument parser.

    .venv/bin/python scripts/cli_reference.py           # write
    .venv/bin/python scripts/cli_reference.py --check   # exit 1 if the file is stale

The page lists every command, its arguments and defaults, so it cannot drift
from the executable. Explanations and contracts stay in cli.md and the guides.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
TARGET = ROOT / 'docs/agent/reference/commands.md'

from ldraw_tools.cli import SPECIALIST, parser  # noqa: E402


def subcommands(p):
    for action in p._actions:
        if isinstance(action, argparse._SubParsersAction):
            helps = {a.dest: a.help for a in action._choices_actions}
            for name, child in action.choices.items():
                yield name, helps.get(name) or child.description, child


def argument(action):
    if action.help == argparse.SUPPRESS or isinstance(action, (argparse._HelpAction, argparse._SubParsersAction)):
        return None
    name = '/'.join(action.option_strings) if action.option_strings else action.dest.upper()
    if action.choices and not isinstance(action, argparse._SubParsersAction):
        name += ' {' + ','.join(map(str, action.choices)) + '}'
    elif action.nargs not in (0, None) and action.option_strings:
        name += ' ' + (action.metavar if isinstance(action.metavar, str) else action.dest.upper())
    details = []
    if action.required and action.option_strings:
        details.append('required')
    if action.default not in (None, False, argparse.SUPPRESS) and action.nargs != 0:
        details.append(f'default {action.default}')
    text = f'`{name}`'
    if details:
        text += ' (' + ', '.join(details) + ')'
    if action.help:
        text += ': ' + ' '.join(action.help.split())
    return text


def section(path, help_text, p, lines):
    children = list(subcommands(p))
    lines.append(f"{'#' * min(len(path) + 2, 5)} `{' '.join(path)}`")
    lines.append('')
    if help_text:
        lines.append(' '.join(help_text.split()))
        lines.append('')
    rows = [argument(a) for a in p._actions]
    rows = [r for r in rows if r]
    lines.extend(f'- {r}' for r in rows)
    if rows:
        lines.append('')
    for name, child_help, child in children:
        section([*path, name], child_help, child, lines)


def render():
    root = parser()
    lines = ['# Commands', '',
             'Generated by `scripts/cli_reference.py` from the argument parser; do not edit. Run `./ldraw-agent COMMAND --help`',
             'for the same text. [cli.md](cli.md) explains contracts, artifacts and exit codes.', '',
             'Global options go before the command: ' + '; '.join(r for r in map(argument, root._actions) if r) + '.', '']
    commands = list(subcommands(root))
    lines += ['## Core commands', '']
    for name, help_text, child in commands:
        if name not in SPECIALIST:
            section([name], help_text, child, lines)
    lines += ['## Specialist commands', '', 'Hidden from `--help`; their guides say when to use them.', '']
    for name, help_text, child in commands:
        if name in SPECIALIST:
            section([name], help_text, child, lines)
    return '\n'.join(lines).rstrip() + '\n'


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--check', action='store_true')
    args = p.parse_args(argv)
    text = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != text:
            print(f'{TARGET} is stale; run scripts/cli_reference.py')
            return 1
        return 0
    TARGET.write_text(text)
    print(f'{TARGET.relative_to(ROOT)}: {len(text)} bytes')
    return 0


if __name__ == '__main__':
    sys.exit(main())
