"""Generate docs/agent/reference/technic-parts.md: the most used Technic parts and their ports.

    .venv/bin/python scripts/technic_parts_reference.py           # rewrite the page
    .venv/bin/python scripts/technic_parts_reference.py --check   # fail when it is stale

Parts are ordered by how often the official Technic sets use them
(ldraw_tools/data/technic-corpus.json); ports come from the merged registry.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from ldraw_tools.common import atomic_write  # noqa: E402
from ldraw_tools.placement import face_name  # noqa: E402
from ldraw_tools.technic import corpus_uses, registry  # noqa: E402

PAGE = ROOT / 'docs' / 'agent' / 'reference' / 'technic-parts.md'
GROUPS = (
    ('Beams and liftarms', 'member', r'^Technic (Beam|Liftarm)', 40),
    ('Bricks, connectors and cross blocks', 'member', r'^Technic (?!Beam|Liftarm|Panel|Fairing)', 30),
    ('Pins and axle-pins', 'connector', r'', 16),
    ('Axles', 'shaft', r'', 16),
    ('Bushes', 'retainer', r'', 6),
    ('Gears and racks', 'gear', r'', 28),
    ('Wheels and hubs', 'wheel', r'', 12),
)
SHORT = {'pin_hole': 'pin hole', 'axle_hole': 'axle hole', 'pin': 'pin', 'axle': 'axle'}


def number(value):
    value = round(float(value), 2)
    return str(int(value)) if value == int(value) else str(value)


def point(values):
    return '[' + ', '.join(number(v) for v in values) + ']'


def ports_text(ports):
    """Ports as short runs: `hole-0..hole-6 pin hole Y 20 at [0, 0, -60] step [0, 0, 20]`."""
    def key(port):
        head, _, tail = port['id'].rpartition('-')
        return (head, int(tail)) if tail.isdigit() else (port['id'], None)

    rows, index = [], 0
    while index < len(ports):
        first = ports[index]
        head, start = key(first)
        end, step = index, None
        while start is not None and end + 1 < len(ports):
            following = ports[end + 1]
            name, value = key(following)
            delta = [b - a for a, b in zip(ports[end]['at'], following['at'])]
            same = (name == head and value == start + (end - index) + 1 and following['kind'] == first['kind']
                    and following['length'] == first['length'] and following['axis'] == first['axis']
                    and not following.get('stops') and not first.get('stops'))
            if not same or (step is not None and any(abs(a - b) > 1e-6 for a, b in zip(delta, step))):
                break
            step, end = delta, end + 1
        label = first['id'] if end == index else f"{first['id']}..{ports[end]['id']}"
        text = f"{label} {SHORT.get(first['kind'], first['kind'])} {face_name(first['axis']).lstrip('+')} " \
               f"{number(first['length'])} at {point(first['at'])}"
        if end > index:
            text += f" step {point(step)}"
        if first.get('stops'):
            text += ' stop ' + ''.join(first['stops'])
        if first.get('friction'):
            text += ' friction'
        rows.append(text)
        index = end + 1
    return '; '.join(rows)


def render():
    entries = registry()['parts']
    uses = corpus_uses()
    lines = ['# Technic parts and their ports', '',
             'Generated by `scripts/technic_parts_reference.py` from the port registry. Do not edit.', '',
             'The parts the official Technic sets use most, by role, with the ports that `on` and `join` name. '
             'Axis letters are the part\'s own axes; positions are local LDU. A run `hole-0..hole-6 … step [0, 0, 20]` '
             'is seven holes 20 LDU apart. `stop -` marks a collar at the low end. `./ldraw-agent part CODE` gives '
             'one part in full, and `./ldraw-agent technic parts --query WORDS` searches the rest.', '']
    seen = set()
    for title, role, pattern, limit in GROUPS:
        rows = [(code, entry) for code, entry in entries.items()
                if entry['role'] == role and code not in seen and re.search(pattern, entry['description'])
                and uses.get(code, 0) > 0]
        rows.sort(key=lambda row: (-uses.get(row[0], 0), row[0]))
        rows = rows[:limit]
        seen.update(code for code, _ in rows)
        lines += [f'## {title}', '', '| Part | Description | Ports | Uses |', '|---|---|---|---|']
        for code, entry in rows:
            ports = ports_text(entry['ports']) or 'none'
            lines.append(f"| `{code}` | {entry['description']} | {ports} | {uses.get(code, 0)} |")
        lines.append('')
    return '\n'.join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not PAGE.exists() or PAGE.read_text() != text:
            print('technic-parts.md is stale; run scripts/technic_parts_reference.py', file=sys.stderr)
            return 1
        return 0
    atomic_write(PAGE, text)
    print(f'{PAGE.relative_to(ROOT)}: {text.count(chr(10) + "| `")} parts')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
