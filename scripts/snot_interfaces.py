"""Generate the SNOT interface table from connector data (never hand-edit the outputs).

    .venv/bin/python scripts/snot_interfaces.py

Writes ldraw_tools/data/snot-interfaces.json and
docs/agent/reference/snot-interfaces.md. Each part lists its studs and sockets
by the face they point out of, in the order `on: {face, stud, socket}`
indexes them, plus where the evidence comes from: an LDCad shadow record, a
library primitive, or the inspected heuristic for deep and square sockets.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from ldraw_tools.common import atomic_write, get_parts  # noqa: E402
from ldraw_tools.placement import facts, interfaces  # noqa: E402

GROUPS = {
    'Side-stud bricks': ['87087', '4070', '30414', '11211', '52107', '22885', '67329', '32952', '4733', '26604', '47905'],
    'Brackets': ['99780', '99781', '99206', '99207', '44728', '36840', '36841', '2436b', '28802'],
    'Offsets and clips': ['3794b', '15573', '87580', '2921', '4081b', '61252', '60470b', '4085d', '11476', '32028'],
    'Skins: plates, tiles and slopes': ['3024', '3023b', '3022', '3710', '3070b', '3069b', '2431', '3068b', '2412b',
                                        '98138', '11477', '85984', '54200', '4589'],
}


def main():
    parts = get_parts()
    table, missing = {}, []
    for group, codes in GROUPS.items():
        for code in codes:
            try:
                data, summary = interfaces(parts, code), facts(parts, code)
            except ValueError:
                missing.append(code)
                continue
            evidence = sorted({r['source'] for r in data['studs'] + data['sockets']})
            table[code] = dict(group=group, description=data['description'], origin=summary.get('origin'),
                               body=summary.get('body', {}).get('size'), studs=summary['studs'],
                               sockets=summary['sockets'], evidence=evidence)
    atomic_write(ROOT / 'ldraw_tools/data/snot-interfaces.json',
                 json.dumps(dict(generated_by='scripts/snot_interfaces.py', parts=table, missing=missing), indent=1) + '\n')
    lines = ['# SNOT interfaces', '',
             'Generated by `scripts/snot_interfaces.py` from the installed library and connector data. Do not edit.',
             '', 'Faces are the part\'s own directions (-Y is up). Indices count from 0 within a face, in the',
             'listed order; use them as `on: {"to": ID, "face": F, "stud": N}` for the support and `socket` for the',
             'part being placed. Coordinates are local LDU. Evidence `heuristic` marks inspected deep or square',
             'sockets; check those seats in a render.', '']
    for group in GROUPS:
        lines += [f'## {group}', '', '| Part | Description | Origin | Studs by face | Sockets by face | Evidence |', '|---|---|---|---|---|---|']
        for code, row in table.items():
            if row['group'] != group:
                continue
            studs = '; '.join(f"{face} {len(at)}: " + ' '.join(f"({','.join(f'{v:g}' for v in p)})" for p in at)
                              for face, at in row['studs'].items()) or '—'
            sockets = '; '.join(f'{face} {len(at)}' for face, at in row['sockets'].items()) or '—'
            lines.append(f"| {code} | {row['description']} | {row['origin']} | {studs} | {sockets} | {', '.join(row['evidence'])} |")
        lines.append('')
    if missing:
        lines += ['Not in the installed library: ' + ', '.join(missing) + '.', '']
    atomic_write(ROOT / 'docs/agent/reference/snot-interfaces.md', '\n'.join(lines))
    print(json.dumps(dict(parts=len(table), missing=missing)))


if __name__ == '__main__':
    main()
